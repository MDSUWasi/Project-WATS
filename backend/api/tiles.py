"""Tiles API blueprint (self-hosted/batch; 404 when tiles are not built).

Endpoints:
  GET /tiles/<nside>/<healpix>.png   serve a pre-built HEALPix coverage tile
  GET /tiles/<z>/<x>/<y>             slippy-map tile (alias; 404 unless built)
  GET /api/tiles/status              tile index status
"""

from __future__ import annotations

from flask import Blueprint, abort, jsonify, send_from_directory

from backend.config import TILES_DIR
from backend.repo import _connect, get_observation_count

bp = Blueprint("tiles", __name__)


@bp.get("/tiles/<int:nside>/<int:healpix>.png")
def healpix_tile(nside, healpix):
    path = TILES_DIR / str(nside) / f"{healpix}.png"
    if not path.is_file():
        abort(404)
    return send_from_directory(path.parent, path.name)


@bp.get("/tiles/<int:z>/<int:x>/<int:y>")
def slippy_tile(z, x, y):
    # Slippy-map tiles are not generated by build_tiles.py (HEALPix scheme).
    # Keep the route for compatibility; 404 unless someone builds them.
    abort(404)


@bp.get("/api/tiles/status")
def tiles_status():
    conn = _connect()
    try:
        count = get_observation_count(conn)
    finally:
        conn.close()
    # Count built tiles across nside dirs.
    built = 0
    nsides = []
    if TILES_DIR.is_dir():
        for d in sorted(TILES_DIR.iterdir()):
            if d.is_dir() and d.name.isdigit():
                pngs = list(d.glob("*.png"))
                built += len(pngs)
                nsides.append({"nside": int(d.name), "tiles": len(pngs)})
    enabled = built > 0
    return jsonify({
        "status": "ready",
        "tiles_enabled": enabled,
        "tiles_dir": str(TILES_DIR),
        "indexed_observations": count,
        "tiles_built": built,
        "nsides": nsides,
    })
